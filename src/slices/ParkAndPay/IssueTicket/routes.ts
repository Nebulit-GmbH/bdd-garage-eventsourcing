import {Request, Response, Router} from 'express';
import {WebApiSetup} from '@event-driven-io/emmett-expressjs';
import {IssueTicketCommand, handleIssueTicket} from './IssueTicketCommand';

export const api = (): WebApiSetup => (router: Router): void => {

    /**
     * @openapi
     * /api/issueticket/{id}:
     *   post:
     *     tags: [Park and Pay]
     *     summary: Issue Ticket
     *     description: Issues a parking ticket when a spot is free (1 spot by default).
     *     parameters:
     *       - in: path
     *         name: id
     *         required: true
     *         schema:
     *           type: string
     *         description: Ticket id (generated by the client; events are stored in the single garage stream)
     *       - in: header
     *         name: correlation_id
     *         required: false
     *         schema:
     *           type: string
     *     requestBody:
     *       required: true
     *       content:
     *         application/json:
     *           schema:
     *             type: object
     *             required: [licensePlate, vehicleType, enteredAt]
     *             properties:
     *               licensePlate:
     *                 type: string
     *               vehicleType:
     *                 type: string
     *                 enum: [CAR, MOTORBIKE]
     *               enteredAt:
     *                 type: string
     *                 format: date-time
     *     responses:
     *       '201':
     *         description: Accepted — TicketIssued appended
     *         content:
     *           application/json:
     *             schema:
     *               type: object
     *               properties:
     *                 ok:
     *                   type: boolean
     *                 next_expected_stream_version:
     *                   type: string
     *                 last_event_global_position:
     *                   type: string
     *       '409':
     *         description: No free spot
     *       '500':
     *         description: Server error
     */
    // Assumption: no auth in this scaffold (no requireUser available), so the endpoint is open.
    router.post('/api/issueticket/:id', async (req: Request, res: Response) => {
        const id = req.params.id;
        const correlationId = req.header('correlation_id') ?? id;
        try {
            const command: IssueTicketCommand = {
                type: 'IssueTicket',
                data: {ticketId: id, licensePlate: req.body.licensePlate, vehicleType: req.body.vehicleType, enteredAt: req.body.enteredAt},
                metadata: {correlation_id: correlationId, causation_id: id},
            };
            const result = await handleIssueTicket(id, command);
            res.set('correlation_id', correlationId);
            res.set('causation_id', id);
            return res.status(201).json({
                ok: true,
                next_expected_stream_version: result.nextExpectedStreamVersion?.toString(),
                last_event_global_position: result.lastEventGlobalPosition?.toString(),
            });
        } catch (err: any) {
            // A retried request for a ticket that was already issued is idempotent, not a conflict.
            if (err?.code === 'ticket_already_issued') {
                return res.status(200).json({ok: true, duplicate: true});
            }
            const msg = errorMapping(err?.code);
            if (msg) return res.status(409).json({error: msg});
            console.error(err);
            return res.status(500).json({ok: false, error: 'Server error'});
        }
    });
};

const errorMapping = (code: string): string | null => {
    switch (code) {
        case 'garage_full': return 'No free spot';
        default: return null;
    }
};
